-- 한복 혜택 문구 중 2건이 실존 업체에 대한 출처 불명 할인 주장이었다.
-- V2__seed.sql에서 만들어진 값으로, 해당 업체와 제휴한 근거가 없다.
--   한복남 경복궁점 → "대여 시 헤어 무료"
--   차 마시는 뜰    → "한복 착용 시 10% 할인"
-- 실제 상호를 쓰면서 확인되지 않은 금전적 혜택을 광고하는 형태라 업체 항의 소지가 있다.
--
-- 경복궁·창경궁의 "한복 착용 시 무료 입장"은 궁능유적본부의 실제 정책이라 그대로 둔다.
--
-- 장소를 목록에서 빼지는 않는다(사용자 여행일정이 참조 중). 대신 금액·조건을 단정하지 않고
-- 매장 확인을 유도하는 문구로 바꾼다. 기존 문구가 그대로일 때만 덮어써서,
-- 나중에 사람이 실제 제휴 내용으로 고쳐 둔 값은 건드리지 않는다.
UPDATE venues
SET hanbok_discount_desc = '경복궁 앞 한복 대여 매장입니다. 제공되는 혜택은 매장에 직접 확인해 주세요.'
WHERE name = '한복남 경복궁점' AND hanbok_discount_desc = '대여 시 헤어 무료';

UPDATE venues
SET hanbok_discount_desc = '북촌 골목의 한옥 찻집입니다. 한복 관련 혜택은 매장에 직접 확인해 주세요.'
WHERE name = '차 마시는 뜰' AND hanbok_discount_desc = '한복 착용 시 10% 할인';
